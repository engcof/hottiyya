# utils/normalize.py
import re

class NormalizeUtils:

    @staticmethod
    def normalize_arabic(text: str) -> str:
        """
        تقوم بتنظيف وتوحيد النصوص العربية لتحسين دقة البحث (إزالة التشكيل وتوحيد الألف).
        """
        if not text:
            return text

        # 1. إزالة التشكيل (الفتحة، الضمة، الكسرة، التنوين، الشدة، السكون)
        # النطاق الكودي \u064B-\u0652 يشمل علامات التشكيل الأساسية
        text = re.sub(r'[\u0617-\u061A\u064B-\u0652]', '', text)

        # 2. توحيد الهمزات والألف الممدودة (أ، إ، آ) إلى ألف عادية (ا)
        text = re.sub(r'[إأآ]', 'ا', text)

        # ❌ (مستبعد بناءً على رغبتك): توحيد الياء والألف المقصورة (ى -> ي)
        # ❌ (مستبعد بناءً على رغبتك): توحيد الهاء والتاء المربوطة (ة -> ه)

        return text